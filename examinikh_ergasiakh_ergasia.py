# Ορισμός σταθερών στοιχείων κάθε λέσχης με χρήση tuples
# Περιέχουν: (Όνομα λέσχης, Υπεύθυνος καθηγητής, Ημέρα λειτουργίας)
r_inf = ("Ρομποτική", "κ. Παπαδόπουλος", "Δευτέρα")
t_inf = ("Θέατρο", "κ. Ιωάννου", "Τρίτη")
m_inf = ("Μουσική", "κ. Δημητρίου", "Τετάρτη")
s_inf = ("Αθλητισμός", "κ. Κωνσταντίνου", "Πέμπτη")

# Ορισμός μαθητών κάθε λέσχης με χρήση sets για αποφυγή διπλότυπων
r_set = {"Άννα", "Γιάννης", "Μαρία"}
t_set = {"Μαρία", "Νίκος", "Ελένη"}
m_set = {"Πέτρος", "Άννα", "Σοφία"}
s_set = {"Γιάννης", "Κώστας", "Ελένη"}

# Οργάνωση των δεδομένων σε lists για εύκολη προσπέλαση
info_lst = [r_inf, t_inf, m_inf, s_inf]
stu_lst = [r_set, t_set, m_set, s_set]

# Κύριος βρόχος επανάληψης του προγράμματος
while True:
    # Εμφάνιση του μενού επιλογών
    print("\n--- ΜΕΝΟΥ ---")
    print("1. Εμφάνιση λεσχών")
    print("2. Στοιχεία λέσχης")
    print("3. Μαθητές λέσχης")
    print("4. Αναζήτηση μαθητή")
    print("5. Προσθήκη μαθητή")
    print("6. Διαγραφή μαθητή")
    print("7. Μοναδικοί μαθητές")
    print("8. Κοινοί μαθητές 2 λεσχών")
    print("9. Μαθητές μόνο 1 λέσχης")
    print("10. Έξοδος")

    choice = input("Επιλογή: ").strip()

    # Χρήση match-case για τη διαχείριση των επιλογών του χρήστη
    match choice:
        case "1":
            print("\nΛέσχες:")
            # Επανάληψη για την εμφάνιση των ονομάτων των λεσχών από τα tuples
            for inf in info_lst:
                print("-", inf[0])

        case "2":
            c = input("Επίλεξε λέσχη (1-4): ").strip()
            # Έλεγχος εισόδου του χρήστη
            if c in ["1", "2", "3", "4"]:
                idx = int(c) - 1
                # Εμφάνιση των πληροφοριών από το αντίστοιχο tuple
                print(f"Λέσχη: {info_lst[idx][0]}, Υπεύθυνος: {info_lst[idx][1]}, Μέρα: {info_lst[idx][2]}")
            else:
                print("Λάθος επιλογή λέσχης.")

        case "3":
            c = input("Επίλεξε λέσχη (1-4): ").strip()
            if c in ["1", "2", "3", "4"]:
                idx = int(c) - 1
                # Εμφάνιση του set μαθητών της επιλεγμένης λέσχης
                print(f"Μαθητές:", stu_lst[idx])
            else:
                print("Λάθος επιλογή λέσχης.")

        case "4":
            name = input("Όνομα: ").strip().title()
            fnd = False
            # Αναζήτηση του μαθητή σε όλα τα sets
            for i in range(4):
                if name in stu_lst[i]:
                    print(f"Βρέθηκε στη λέσχη: {info_lst[i][0]}")
                    fnd = True
            if not fnd:
                print("Δεν βρέθηκε.")

        case "5":
            c = input("Λέσχη για προσθήκη (1-4): ").strip()
            if c in ["1", "2", "3", "4"]:
                name = input("Όνομα: ").strip().title()
                idx = int(c) - 1
                # Προσθήκη του μαθητή στο set (διπλότυπα απορρίπτονται αυτόματα)
                stu_lst[idx].add(name)
                print("Η προσθήκη ολοκληρώθηκε.")
            else:
                print("Λάθος επιλογή λέσχης.")

        case "6":
            c = input("Λέσχη για διαγραφή (1-4): ").strip()
            if c in ["1", "2", "3", "4"]:
                name = input("Όνομα: ").strip().title()
                idx = int(c) - 1
                # Έλεγχος αν υπάρχει ο μαθητής πριν τη διαγραφή για αποφυγή σφάλματος
                if name in stu_lst[idx]:
                    stu_lst[idx].remove(name)
                    print("Η διαγραφή ολοκληρώθηκε.")
                else:
                    print("Δεν υπάρχει αυτός ο μαθητής στη λέσχη.")
            else:
                print("Λάθος επιλογή λέσχης.")

        case "7":
            # Ένωση όλων των συνόλων για να βρούμε τους μοναδικούς μαθητές του σχολείου
            all_s = r_set | t_set | m_set | s_set
            print("Όλοι οι μοναδικοί μαθητές:", all_s)

        case "8":
            c1 = input("Λέσχη 1 (1-4): ").strip()
            c2 = input("Λέσχη 2 (1-4): ").strip()
            if c1 in ["1","2","3","4"] and c2 in ["1","2","3","4"]:
                if c1 == c2:
                    print("Έδωσες την ίδια λέσχη.")
                else:
                    i1, i2 = int(c1)-1, int(c2)-1
                    # Εύρεση της τομής των δύο συνόλων για τους κοινούς μαθητές
                    com = stu_lst[i1] & stu_lst[i2]
                    print("Κοινοί μαθητές:", com)
            else:
                print("Λάθος επιλογή λέσχης.")

        case "9":
            c = input("Λέσχη (1-4): ").strip()
            if c in ["1", "2", "3", "4"]:
                idx = int(c) - 1
                target_s = stu_lst[idx]
                other_s = set()
                # Δημιουργία ενός συνόλου με τους μαθητές όλων των ΑΛΛΩΝ λεσχών
                for j in range(4):
                    if j != idx:
                        other_s = other_s | stu_lst[j]
                # Αφαίρεση (διαφορά) των μαθητών των άλλων λεσχών από τη στοχευμένη λέσχη
                only_here = target_s - other_s
                print("Μαθητές που ανήκουν ΜΟΝΟ σε αυτή τη λέσχη:", only_here)
            else:
                print("Λάθος επιλογή λέσχης.")

        case "10":
            print("Πραγματοποιήθηκε έξοδος από το πρόγραμμα.")
            break # Τερματισμός της loop
            
        case _:
            print("Λάθος επιλογή μενού. Παρακαλώ επίλεξε από 1 έως 10.")